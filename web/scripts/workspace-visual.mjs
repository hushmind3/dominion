import {withBrowser,assert} from './ui-smoke-utils.mjs'
await withBrowser('workspace-visual',async({page,db,url,viewport})=>{
 await page.goto(url+'/#/chat')
 await page.locator('.conversation-composer').waitFor({state:'visible'})
 const nav=page.locator('#workspace-navigation')
 if(!(await nav.isVisible())){
  await page.locator('.conversation-composer-options button').first().click()
  await nav.waitFor({state:'visible'})
 }
 const connections=nav.getByRole('button',{name:/서비스 연결|Connected services/})
 await connections.click()
 await page.waitForURL(/#\/connections/)
 const connectionTabs=page.getByRole('navigation',{name:/서비스 연결 보기|Connection views/})
 await connectionTabs.getByRole('button',{name:/^MCP 연결$|^MCP connections$/}).click()
 await page.waitForURL(/#\/connections\?view=mcp/)
 // Native capabilities are no longer duplicated in the MCP manager.
 assert.equal(await page.getByRole('button',{name:/도구 목록 보기|View available tools/}).count(),0)
 const plugin=page.getByRole('checkbox',{name:/MCP.*Mock Test MCP/})
 await plugin.waitFor({state:'visible'})
 assert.equal(await plugin.isChecked(),true)
 await plugin.click() // React commits the server-confirmed state asynchronously.
 await page.waitForFunction(()=>document.querySelector('input[aria-label*="Mock Test MCP"]')?.checked===false)
 assert.equal(db.mcp[0].enabled,false)
 await plugin.click()
 await page.waitForFunction(()=>document.querySelector('input[aria-label*="Mock Test MCP"]')?.checked===true)
 assert.equal(db.mcp[0].enabled,true)
 assert.equal(db.mcpWrites.length,2)
 await page.goto(url+'/#/settings?view=features')
 await page.getByRole('button',{name:/Web Search/}).waitFor({state:'visible'})
 assert.equal(await page.locator('.workspace-reply-preferences').count(),0,'AI and capability tabs must not contain chat preferences')
 const settingsTabs=page.getByRole('navigation',{name:/설정과 기능 관리|Settings and capabilities/})
 await settingsTabs.getByRole('button',{name:/^답변 설정$|^Reply settings$/}).click()
 await page.waitForURL(/#\/settings\?view=reply/)
 await page.locator('.workspace-conversation-settings .conversation-settings-inline').waitFor({state:'visible'})
 await settingsTabs.getByRole('button',{name:/^AI 연결$|^AI connections$/}).click()
 await page.waitForURL(/#\/settings\?view=ai/)
 await page.locator('.workspace-reply-preferences').waitFor({state:'detached'})
 await page.goto(url+'/#/extensions?tab=market')
 await page.waitForURL(/#\/connections\?view=registry/)
 assert.equal(await page.getByRole('navigation',{name:/서비스 연결 보기|Connection views/}).getByRole('button',{name:/^MCP 레지스트리$|^MCP registry$/}).getAttribute('aria-current'),'page')
 await page.goto(url+'/#/connections?view=plugins')
 await page.getByRole('heading',{name:/플러그인 마켓|Plugin marketplace/}).waitFor({state:'visible'})
 const extTabs=page.getByRole('navigation',{name:/확장 프로그램 보기|Extension views/})
 await page.getByRole('button',{name:/설치 · 다운로드|Install \/ download/}).click()
 await page.getByRole('link',{name:/fixture.zip/}).waitFor({state:'visible'})
 assert.equal(await page.getByRole('link',{name:/fixture.zip/}).getAttribute('href'),'https://github.com/example/fixture/releases/download/v1/fixture.zip')
 await extTabs.getByRole('button',{name:/^설치됨$|^Installed$/}).click()
 await page.getByText(/내 플러그인|My plugins/).waitFor({state:'visible'})
 await page.getByRole('button',{name:/^설치$|^Install$/}).click()
 await page.getByLabel(/표시 이름|^Name$/).fill('Voice test')
 await page.getByLabel(/Docker 이미지와 버전|Docker image and version/).fill('example/voice:1.2.3')
 await page.getByRole('checkbox',{name:/이미지 출처와 실행 권한|I reviewed the image source/}).check()
 await page.getByRole('button',{name:/설치 확인|^Install$/}).click()
 const installed=page.locator('article').filter({hasText:'Voice test'})
 await installed.getByText(/설치됨|^Installed$/).waitFor({state:'visible'})
 assert.equal(db.pluginWrites[0].body.image,'example/voice:1.2.3')
 assert.equal(db.pluginWrites[0].body.network,false)
 page.once('dialog',d=>d.accept())
 await installed.getByRole('button',{name:/^실행$|^Start$/}).click()
 await installed.getByText(/실행 중|^Running$/).waitFor({state:'visible'})
 await installed.getByRole('button',{name:/^로그$|^Logs$/}).click()
 await page.getByText('Voice fixture ready').waitFor({state:'visible'})
 await installed.getByRole('button',{name:/^중지$|^Stop$/}).click()
 await installed.getByText(/중지됨|Stopped/).waitFor({state:'visible'})
 page.once('dialog',d=>d.accept())
 await installed.getByRole('button',{name:/^제거$|^Remove$/}).click()
 await installed.getByText(/데이터 보존됨|Data retained/).waitFor({state:'visible'})
 await installed.getByRole('button',{name:/다시 설치·버전 변경|Reinstall \/ change version/}).click()
 await page.getByLabel(/Docker 이미지와 버전|Docker image and version/).fill('example/voice:1.2.4')
 await page.getByRole('checkbox',{name:/이미지 출처와 실행 권한|I reviewed the image source/}).check()
 await page.getByRole('button',{name:/설치 확인|^Install$/}).click()
 await installed.getByText(/설치됨|^Installed$/).waitFor({state:'visible'})
 assert.equal(db.pluginWrites.at(-1).body.id,db.pluginWrites[0].body.id)
 assert.equal(db.pluginWrites.at(-1).body.image,'example/voice:1.2.4')
 await extTabs.getByRole('button',{name:/개발자 검색|Developer search/}).click()
 const searchInput=page.getByRole('textbox',{name:/확장 프로그램 검색어|Search packages/})
 await searchInput.fill('voice')
 await page.getByRole('button',{name:/^검색$|^Search$/}).click()
 await page.getByText('voice-fixture',{exact:true}).waitFor({state:'visible'})
 await page.getByText(/호환성 미검증|Compatibility not verified/).waitFor({state:'visible'})
 const width=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth)
 assert.ok(width<12,'horizontal overflow '+width+' at '+viewport.width)
},[{width:1440,height:900},{width:820,height:820},{width:390,height:844}])
