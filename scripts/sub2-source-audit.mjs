// DOMINION sub2: source-tree duplicate audit. Node only; no build or network.
// Read-only analysis of executable surfaces, not archived docs or user SQLite.
import {createHash} from 'node:crypto';
import {existsSync,readFileSync,readdirSync} from 'node:fs';
import {join,resolve,relative,sep} from 'node:path';
import {fileURLToPath} from 'node:url';

const root=resolve(fileURLToPath(new URL('../',import.meta.url)));
const folders=[
  'src','crates','web/src','web/tests','sdk','cloud/src','cloud/tests',
  'services','scripts','src-tauri/src','.github/workflows','assets/channels',
];
const files=[];
const codeExt=/\.(?:rs|tsx?|jsx?|mjs|sql|ya?ml|json)$/;
const codeForClone=/\.(?:rs|tsx?|jsx?|mjs)$/;
const skipNames=new Set(['node_modules','target','dist','build','.next','.git']);
function walk(path) {
  if(!existsSync(join(root,path)))return;
  for(const entry of readdirSync(join(root,path),{withFileTypes:true})){
    if(skipNames.has(entry.name))continue;
    const next=join(path,entry.name);
    if(entry.isDirectory())walk(next);
    else if(entry.isFile()&&codeExt.test(entry.name))files.push(next);
  }
}
for(const folder of folders)walk(folder);
files.sort();
const content=new Map(files.map(path=>[path,readFileSync(join(root,path),'utf8')]));
const failures=[];

// Exact nontrivial duplicates are almost always drift waiting to happen.
const byDigest=new Map();
for(const [path,source] of content){
  if(source.length<256)continue;
  const hash=createHash('sha256').update(source).digest('hex');
  const existing=byDigest.get(hash);
  if(existing)failures.push('identical executable files: '+existing+' & '+path);
  else byDigest.set(hash,path);
}

// Expand router collection paths as the application actually does at runtime.
// The old gate only checked literal .route("/api/..."), missing duplicates
// generated by the per-collection route factory.
const router=content.get('src/api/mod.rs')||'';
const addons=content.get('src/api/addons.rs')||'';
const domains=[...content].filter(([name])=>name.startsWith('src/api/surfaces/'))
  .map(([,source])=>source).join('\n');
if(!addons.includes('pub(super) fn routes()'))failures.push('optional API router missing');
const collections=content.get('src/api/services/management/collections.rs')||'';
const staticPaths=[...(router+'\n'+addons+'\n'+domains).matchAll(/\.route\(\s*["'](\/api\/[^"']+)["']/g)]
  .map(match=>match[1]);
const collectionBlock=collections.match(/pub const COLLECTIONS:\s*&\[&str\]\s*=\s*&\[([\s\S]*?)\];/);
if(!collectionBlock)failures.push('cannot enumerate collection route kinds');
const collectionKinds=[...(collectionBlock?.[1]||'').matchAll(/"([a-z_-]+)"/g)].map(m=>m[1]);
const allRoutes=[
  ...staticPaths,
  ...collectionKinds.flatMap(kind=>['/api/'+kind,'/api/'+kind+'/:id']),
];
const routeMap=new Map();
for(const path of allRoutes){
  // Axum routing treats :id and :name as the same path shape.
  const shape=path.replace(/:[a-z_]+/g,':parameter');
  if(routeMap.has(shape)){
    failures.push('duplicate API route shape: '+routeMap.get(shape)+' & '+path);
  }else routeMap.set(shape,path);
}
// Contract-check every Team UI action against the real mounted API router.
// This fails closed when a React button points to a non-existent endpoint.
const teamRoutes=[
 '/api/activity/teams','/api/activity/teams/start',
 '/api/activity/teams/:id/stop','/api/activity/teams/:id/resume',
 '/api/activity/teams/:id/artifacts/:task_id',
 '/api/activity/teams/:id/artifacts/:task_id/apply',
 '/api/activity/teams/:id/artifacts/:task_id/reject'
];
for(const route of teamRoutes){
 if(!routeMap.has(route.replace(/:[a-z_]+/g,':parameter'))){
  failures.push('React Team UI route not mounted by Axum: '+route);
 }
}
const teamControls=content.get('src/api/services/automation/team_controls.rs')||'';
const activityUi=content.get('web/src/components/TeamActivity.tsx')||'';
const operationUi=content.get('web/src/pages/Operations.tsx')||'';
const chatUi=content.get('web/src/pages/Chat.tsx')||'';
const teamTools=content.get('src/engine/services/tools/tools_team.rs')||'';
for(const action of ['start','stop','resume','preview','approve_apply','reject']){
 if(!teamControls.includes('pub async fn '+action+'('))failures.push('Team HTTP handler missing: '+action);
}
if(!operationUi.includes('<TeamActivity/>'))failures.push('Existing Activity page does not mount Team UI');
if(!chatUi.includes('<TeamRunStrip '))failures.push('Existing Chat page does not expose Team status');
for(const token of ['/start','/resume','/apply','/reject','reviewDigest','remoteWorkers']){
 if(!activityUi.includes(token))failures.push('Team UI is missing control: '+token);
}
if(!teamTools.includes('validate_ui_worker_route'))failures.push('UI-selected Worker routing is not enforced by Rust');
if(!teamControls.includes('begin_session('))failures.push('UI team resume does not claim Lead session ownership');
if(router.includes('collections::action'))
  failures.push('unreachable generic collection action route reintroduced');
if(/pub async fn action\s*\(/.test(collections))
  failures.push('dead collection action handler reintroduced');

// High-confidence cross-file repeated long blocks are audit signals.
// Do not rewrite lookalike functionality without proving its contracts.
// Source lines inside in-file Rust tests are excluded from this signal.
const windowSize=12,first=new Map(),clones=new Map();
for(const [path,raw] of content){
  if(!codeForClone.test(path)||/(?:^|\/)(?:tests?|__tests__)\//.test(path)
      ||/\.test\.[cm]?[jt]s$/.test(path))continue;
  const production=path.endsWith('.rs')?raw.split(/\n#\[cfg\(test\)\]/)[0]:raw;
  const lines=production.split('\n').map(line=>line.trim());
  for(let i=0;i+windowSize<=lines.length;i++){
    const block=lines.slice(i,i+windowSize);
    if(block.filter(Boolean).length<10)continue;
    const signature=block.join('\n');
    if(signature.length<450)continue;
    const key=createHash('sha256').update(signature).digest('hex');
    const before=first.get(key);
    if(!before){first.set(key,{path,line:i+1});continue;}
    if(before.path===path)continue;
    const pair=[before.path,path].sort().join(' <> ');
    const item=clones.get(pair)||{pair,windows:0,example:before.line};
    item.windows++;
    clones.set(pair,item);
  }
}
const largest=[...content].sort((a,b)=>b[1].length-a[1].length)
  .slice(0,8).map(([path,source])=>({path,bytes:source.length}));
const hotspots=[...clones.values()].sort((a,b)=>b.windows-a.windows)
  .filter(item=>item.windows>=2).slice(0,12);
console.log('DOMINION sub2 source audit',JSON.stringify({
  activeFiles:files.length, apiRoutes:allRoutes.length,
  explicitRoutes:staticPaths.length, collectionKinds,
  exactDuplicateFiles:failures.filter(x=>x.startsWith('identical')).length,
  crossFileCloneHotspots:hotspots, largestFiles:largest
}));
if(failures.length){
  for(const issue of failures)console.error('AUDIT FAILURE:',issue);
  process.exitCode=1;
}
